// ─── Input validation ──────────────────────────────────────────────────────

type ToolArgs = Record<string, unknown>

function checkKeys(args: ToolArgs, allowed: string[]): void {
  const unknown = Object.keys(args).filter(k => !allowed.includes(k))
  if (unknown.length > 0) throw new ToolInputError(`Unknown argument(s): ${unknown.join(', ')}`)
}

function requirePathArg(args: ToolArgs): string {
  const value = args.path
  if (typeof value !== 'string' || value.trim() === '') throw new ToolInputError('"path" must be a non-empty string')
  if (value.length > MAX_PATH_LENGTH) throw new ToolInputError(`"path" is longer than ${MAX_PATH_LENGTH} characters`)
  if (value.includes('\0')) throw new ToolInputError('"path" contains a null byte')
  return value
}

function toPosix(path: string): string {
  return path.split(sep).join('/')
}

function isInside(root: string, target: string): boolean {
  const rel = relative(root, target)
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel))
}

/**
 * Resolve a user-supplied path to a project-relative POSIX path, refusing
 * anything outside the root — lexically, and through symlinks when it exists.
 */
export function resolveProjectPath(projectRoot: string, input: string): { rel: string; abs: string; exists: boolean } {
  const abs = resolve(projectRoot, input)
  if (!isInside(projectRoot, abs)) throw new ToolInputError(`"${input}" is outside the project root`)
  const exists = existsSync(abs)
  if (exists) {
    const realRoot = realpathSync(projectRoot)
    if (!isInside(realRoot, realpathSync(abs))) throw new ToolInputError(`"${input}" resolves outside the project root`)
  }
  const rel = toPosix(relative(projectRoot, abs))
  if (rel === '') throw new ToolInputError('"path" must name a file, not the project root')
  return { rel, abs, exists }
}

// ─── Shared helpers ────────────────────────────────────────────────────────

const NO_GRAPH =
  `${GRAPH_FILENAME} not found. Ask the developer to run \`npx aidoc-kit index\` ` +
  '(requires @colbymchenry/codegraph). Do not run it yourself.'

function fileEntry(graph: EnrichedGraph, rel: string): EnrichedFile | undefined {
  return graph.files.find(f => f.file === rel)
}

function rankByCriticality(graph: EnrichedGraph, files: string[]): string[] {
  const score = new Map(graph.files.map(f => [f.file, f]))
  return [...files]
    .sort((a, b) => (score.get(b)?.criticality ?? -1) - (score.get(a)?.criticality ?? -1) || a.localeCompare(b))
    .map(f => {
      const entry = score.get(f)
      return entry ? `- \`${f}\` — ${entry.criticalityLevel} (${entry.criticality}), ${entry.role}` : `- \`${f}\``
    })
}

function describeEntry(entry: EnrichedFile): string[] {
  return [
    `- Role: ${entry.role} (${entry.roleReason})`,
    `- Criticality: ${entry.criticalityLevel} (${entry.criticality}/100)`,
    `- Dependents: ${entry.inDegree}, dependencies: ${entry.outDegree}`,
    ...(entry.tags.length > 0 ? [`- Tags: ${entry.tags.join(', ')}`] : []),
  ]
}

/** The scanner keeps the list "- " prefixes of multi-line tag values. */
function cleanTagValue(value: string): string {
  return value.replace(/^-\s+/, '').replace(/\s+/g, ' ').trim()
}

function describeAiDocs(abs: string, projectRoot: string): string[] {
  const docs = extractAiDocs(abs, projectRoot)
  if (!docs) return ['_No @ai-* block in this file._']
  const list = (items: string[]): string[] => items.map(cleanTagValue).filter(Boolean).map(i => `  - ${i}`)
  const lines: string[] = []
  if (docs.agent) lines.push(`- Agent: ${docs.agent}${docs.related.length > 0 ? ` (related: ${docs.related.join(', ')})` : ''}`)
  if (docs.runtime) lines.push(`- Runtime: ${docs.runtime}`)
  if (docs.context) lines.push(`- Context: ${docs.context}`)
  if (docs.whenModifying.length > 0) lines.push('- When modifying:', ...list(docs.whenModifying))
  if (docs.neverDo.length > 0) lines.push('- Never:', ...list(docs.neverDo))
  if (docs.cascade.length > 0) lines.push('- Cascade (check after editing):', ...list(docs.cascade))
  if (docs.validate) lines.push(`- Validate with: \`${docs.validate}\``)
  return lines
}

function sourceFilesChangedSince(projectRoot: string, isoDate: string): string[] {
  const since = Date.parse(isoDate)
  if (Number.isNaN(since)) return []
  return walkDir(projectRoot)
    .filter(f => {
      try { return statSync(f).mtimeMs > since } catch { return false }
    })
    .map(f => toPosix(relative(projectRoot, f)))
}

function freshnessLine(graph: EnrichedGraph, projectRoot: string): string {
  const changed = sourceFilesChangedSince(projectRoot, graph.generatedAt)
  if (changed.length === 0) return `Graph generated ${graph.generatedAt}; no source file modified since.`
  return (
    `Graph generated ${graph.generatedAt}; ${changed.length} source file(s) modified since — ` +
    'it may be stale. Ask the developer to run `npx aidoc-kit index --incremental`.'
  )
}

function walkTextFiles(dir: string, out: string[]): void {
  if (out.length >= TEXT_REF_MAX_FILES) return
  let entries: string[]
  try { entries = readdirSync(dir) } catch { return }
  for (const entry of entries) {
    if (out.length >= TEXT_REF_MAX_FILES) return
    if (TEXT_REF_SKIP_DIRS.has(entry) || entry.startsWith('.env')) continue
    const full = join(dir, entry)
    let stat
    try { stat = statSync(full) } catch { continue }
    if (stat.isDirectory()) walkTextFiles(full, out)
    else if (TEXT_REF_EXTENSIONS.has(extname(entry)) && !TEXT_REF_SKIP_FILES.has(entry) && stat.size <= TEXT_REF_MAX_FILE_BYTES) {
      out.push(full)
    }
  }
}

/** Lines generated by aidoc-kit blocks (cascade lists, "Importe dans") that name paths. */
function isGeneratedDocLine(line: string): boolean {
  return /^\s*\*\s+-\s/.test(line) || /Import(é|e) dans\s*:/.test(line)
}

/**
 * Places that name the file as a string — the coupling the import graph cannot see.
 * Files already known as graph dependents are left out.
 */
export function findTextReferences(projectRoot: string, rel: string, exclude: Set<string>): string[] {
  const withoutExt = rel.slice(0, rel.length - extname(rel).length)
  const needles = [...new Set([rel, withoutExt])].filter(n => n.length >= 4)
  const files: string[] = []
  walkTextFiles(projectRoot, files)

  const refs: string[] = []
  for (const abs of files) {
    const fileRel = toPosix(relative(projectRoot, abs))
    if (fileRel === rel || exclude.has(fileRel)) continue
    let content: string
    try { content = readFileSync(abs, 'utf-8') } catch { continue }
    if (!needles.some(n => content.includes(n))) continue
    const lines = content.split('\n')
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i]
      if (!needles.some(n => line.includes(n)) || isGeneratedDocLine(line)) continue
      const text = line.trim()
      refs.push(`- \`${fileRel}:${i + 1}\` ${text.length > 160 ? text.slice(0, 157) + '...' : text}`)
      if (refs.length >= TEXT_REF_MAX_RESULTS) return refs
    }
  }
  return refs
}

function chunkMarkdown(projectRoot: string, rel: string, abs: string, graph: EnrichedGraph | null): string | null {
  const stored = join(projectRoot, '.codemod', 'chunks', rel + '.md')
  if (existsSync(stored)) {
    const storedMtime = statSync(stored).mtimeMs
    if (storedMtime >= statSync(abs).mtimeMs) return readFileSync(stored, 'utf-8')
  }
  const chunk = chunkFile(abs, graph ? getDependents(graph, rel) : [], projectRoot)
  if (!chunk) return null
  const md = renderChunk(chunk)
  return graph ? md : md.replace('_Not imported (detected)_', `_Unknown: ${GRAPH_FILENAME} not found_`)
}

function clip(text: string, maxChars: number): string {
  if (text.length <= maxChars) return text
  return text.slice(0, maxChars) + '\n\n_[truncated to fit the size budget]_'
}

// ─── Tools ─────────────────────────────────────────────────────────────────

function contextForEdit(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['path', 'maxTokens'])
  const { rel, abs, exists } = resolveProjectPath(projectRoot, requirePathArg(args))
  const maxTokens = args.maxTokens ?? DEFAULT_MAX_TOKENS
  if (typeof maxTokens !== 'number' || !Number.isInteger(maxTokens) || maxTokens < MIN_MAX_TOKENS || maxTokens > MAX_MAX_TOKENS) {
    throw new ToolInputError(`"maxTokens" must be an integer between ${MIN_MAX_TOKENS} and ${MAX_MAX_TOKENS}`)
  }
  const budget = maxTokens * CHARS_PER_TOKEN
  const graph = readEnrichedGraph(projectRoot)
  const entry = graph ? fileEntry(graph, rel) : undefined
  const dependents = graph ? getDependents(graph, rel) : []

  // Sections in priority order: when the budget runs out, the last ones are cut.
  const sections: string[] = [`# Context for editing \`${rel}\``]
  if (!exists) sections.push('_This file does not exist (yet). Graph data below may describe a deleted file._')

  if (!graph) sections.push(`## Graph\n${NO_GRAPH}`)
  else if (!entry) sections.push(`## Graph\nNot in the graph (new, ignored or non-source file). ${freshnessLine(graph, projectRoot)}`)
  else {
    const warn = entry.criticalityLevel === 'high' || entry.criticalityLevel === 'critical'
      ? '\n\n**High criticality: read every dependent below before editing.**'
      : ''
    sections.push(`## Graph\n${describeEntry(entry).join('\n')}\n\n${freshnessLine(graph, projectRoot)}${warn}`)
  }

  if (exists) sections.push(`## @ai-* rules\n${describeAiDocs(abs, projectRoot).join('\n')}`)
  if (graph) {
    sections.push(`## Dependents (${dependents.length})\n${dependents.length > 0 ? rankByCriticality(graph, dependents).join('\n') : '_None in the graph._'}`)
  }

  const textRefs = findTextReferences(projectRoot, rel, new Set(dependents))
  sections.push(
    `## Named as text elsewhere (${textRefs.length}${textRefs.length >= TEXT_REF_MAX_RESULTS ? '+' : ''})\n` +
    (textRefs.length > 0
      ? 'Not import edges: configs, scripts or data naming this path. Renaming or moving the file breaks them.\n' + textRefs.join('\n')
      : '_No textual reference found._'),
  )

  if (exists) {
    const chunk = chunkMarkdown(projectRoot, rel, abs, graph)
    if (chunk) sections.push(`## Large-file summary\n${chunk.replace(/^# .*\n/, '')}`)
  }

  let out = ''
  for (const section of sections) {
    const next = out ? `${out}\n\n${section}` : section
    if (next.length > budget) {
      out = clip(next, budget)
      break
    }
    out = next
  }
  return out
}

function fileInfo(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['path'])
  const { rel, abs, exists } = resolveProjectPath(projectRoot, requirePathArg(args))
  const graph = readEnrichedGraph(projectRoot)
  const entry = graph ? fileEntry(graph, rel) : undefined
  const parts = [`# \`${rel}\``]
  parts.push(`## Graph\n${!graph ? NO_GRAPH : entry ? describeEntry(entry).join('\n') : 'Not in the graph.'}`)
  parts.push(`## @ai-* block\n${exists ? describeAiDocs(abs, projectRoot).join('\n') : '_File does not exist._'}`)
  return parts.join('\n\n')
}

function neighbours(projectRoot: string, args: ToolArgs, direction: 'dependents' | 'dependencies'): string {
  checkKeys(args, ['path'])
  const { rel } = resolveProjectPath(projectRoot, requirePathArg(args))
  const graph = readEnrichedGraph(projectRoot)
  if (!graph) return NO_GRAPH
  const files = direction === 'dependents' ? getDependents(graph, rel) : getDependencies(graph, rel)
  const header = `# ${direction === 'dependents' ? 'Dependents' : 'Dependencies'} of \`${rel}\` (${files.length})`
  const note = fileEntry(graph, rel) ? '' : '\n\n_This file is not in the graph._'
  const footer = direction === 'dependents'
    ? '\n\nThe graph only sees imports, calls and references: use context_for_edit to also find textual references.'
    : ''
  return `${header}${note}\n\n${files.length > 0 ? rankByCriticality(graph, files).join('\n') : '_None._'}${footer}`
}

function criticalFiles(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['minLevel'])
  const minLevel = args.minLevel ?? 'high'
  if (minLevel !== 'medium' && minLevel !== 'high' && minLevel !== 'critical') {
    throw new ToolInputError('"minLevel" must be one of: medium, high, critical')
  }
  const graph = readEnrichedGraph(projectRoot)
  if (!graph) return NO_GRAPH
  const files = getCriticalFiles(graph, minLevel)
  const list = files.map(f =>
    `- \`${f.file}\` — ${f.criticalityLevel} (${f.criticality}), ${f.role}, ${f.inDegree} dependent(s)` +
    (f.tags.length > 0 ? `, ${f.tags.join('/')}` : ''),
  )
  return `# Files at or above "${minLevel}" (${files.length})\n\n${list.length > 0 ? list.join('\n') : '_None._'}`
}

function readChunk(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['path'])
  const { rel, abs, exists } = resolveProjectPath(projectRoot, requirePathArg(args))
  if (!exists) throw new ToolInputError(`"${rel}" does not exist`)
  if (!statSync(abs).isFile()) throw new ToolInputError(`"${rel}" is not a file`)
  return chunkMarkdown(projectRoot, rel, abs, readEnrichedGraph(projectRoot))
    ?? `\`${rel}\` is under 150 lines: read it directly.`
}

function graphStatus(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, [])
  const graph = readEnrichedGraph(projectRoot)
  if (!graph) return NO_GRAPH
  const { stats } = graph
  return [
    `# ${GRAPH_FILENAME}`,
    `- Files: ${stats.files} (${stats.client} client / ${stats.server} server / ${stats.universal} universal)`,
    `- File-level edges: ${stats.edges}`,
    `- CodeGraph version: ${graph.codegraph.version ?? 'unknown'}`,
    '',
    freshnessLine(graph, projectRoot),
  ].join('\n')
}

function requireName(args: ToolArgs): string {
  const value = args.name
  if (typeof value !== 'string' || value.trim() === '') throw new ToolInputError('"name" must be a non-empty string')
  if (value.length > 200) throw new ToolInputError('"name" is longer than 200 characters')
  return value.trim()
}

function optionalFile(projectRoot: string, args: ToolArgs): string | undefined {
  return args.file === undefined ? undefined : resolveProjectPath(projectRoot, requirePathArg({ path: args.file })).rel
}

function findSymbolTool(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['name', 'file'])
  return findSymbol(projectRoot, requireName(args), optionalFile(projectRoot, args))
}

function traceTool(projectRoot: string, args: ToolArgs): string {
  checkKeys(args, ['name', 'direction', 'depth', 'file'])
  const direction = args.direction ?? 'callees'
  if (direction !== 'callees' && direction !== 'callers') throw new ToolInputError('"direction" must be callees or callers')
  const depth = args.depth ?? 3
  if (typeof depth !== 'number' || !Number.isInteger(depth) || depth < 1 || depth > 5) throw new ToolInputError('"depth" must be an integer between 1 and 5')
  return traceSymbol(projectRoot, requireName(args), direction, depth, optionalFile(projectRoot, args))
}

const HANDLERS: Record<string, (projectRoot: string, args: ToolArgs) => string> = {
  find_symbol: findSymbolTool,
  trace: traceTool,
  context_for_edit: contextForEdit,
  file_info: fileInfo,
  dependents: (root, args) => neighbours(root, args, 'dependents'),
  dependencies: (root, args) => neighbours(root, args, 'dependencies'),
  critical_files: criticalFiles,
  read_chunk: readChunk,
  graph_status: graphStatus,
}

export function isKnownTool(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(HANDLERS, name)
}

/** Run a tool. Throws ToolInputError on invalid arguments. */
export function callTool(projectRoot: string, name: string, args: ToolArgs): string {
  const handler = HANDLERS[name]
  if (!handler) throw new ToolInputError(`Unknown tool: ${name}`)
  return clip(handler(projectRoot, args), MAX_RESPONSE_CHARS)
}

/** Tools exposed by default; `aidoc-kit mcp --all-tools` adds the others. */
export const DEFAULT_TOOLS = ['find_symbol', 'trace', 'context_for_edit', 'read_chunk']

export function toolDefinitions(allTools: boolean): ToolDefinition[] {
  return allTools ? TOOL_DEFINITIONS : TOOL_DEFINITIONS.filter(t => DEFAULT_TOOLS.includes(t.name))
}
